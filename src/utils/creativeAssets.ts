// ─── PROFILE ARCHETYPES ──────────────────────────────────────
// Used to intelligently pick GIFs and styles based on repo languages
export type ProfileArchetype =
  | 'frontend'    // React, Vue, Angular, CSS heavy
  | 'backend'     // Java, Go, Node, Python server-side
  | 'fullstack'   // Mix of both
  | 'ml-ai'       // Python + TF/PyTorch/notebooks
  | 'devops'      // Docker, K8s, CI/CD
  | 'mobile'      // Flutter, Swift, Kotlin
  | 'general';    // Everything else

export const detectArchetype = (languages: string[], repos: { name: string; description: string | null }[]): ProfileArchetype => {
  const langStr = languages.join(' ').toLowerCase();
  const repoStr = repos.map(r => `${r.name} ${r.description || ''}`).join(' ').toLowerCase();
  const combined = `${langStr} ${repoStr}`;

  if (/tensorflow|pytorch|keras|jupyter|scikit|ml|machine.learning|deep.learning|llm|ai|gpt|bert|nlp/.test(combined)) return 'ml-ai';
  if (/docker|kubernetes|k8s|terraform|ansible|jenkins|ci.cd|devops|infrastructure/.test(combined)) return 'devops';
  if (/flutter|swift|kotlin|react.native|mobile|ios|android/.test(combined)) return 'mobile';
  if (/react|vue|angular|svelte|frontend|css|html|ui|ux|next.js/.test(langStr)) {
    if (/node|express|django|flask|spring|backend|api|server/.test(combined)) return 'fullstack';
    return 'frontend';
  }
  if (/node|express|django|flask|spring|go|rust|java|backend|api|server|graphql/.test(combined)) return 'backend';
  return 'general';
};


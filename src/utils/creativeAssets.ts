// ─── RANDOM PICKER ──────────────────────────────────────────
export const pick = <T>(arr: T[]): T => arr[Math.floor(Math.random() * arr.length)];
export const pickN = <T>(arr: T[], n: number): T[] => {
  const shuffled = [...arr].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, n);
};

